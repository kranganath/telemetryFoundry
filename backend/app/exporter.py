"""Databricks-ready artifact generation.

Prefers the LLM when the Meta API is configured; otherwise renders from
built-in templates. Every export bundles:
  - PySpark transform job
  - Equivalent Spark SQL
  - Data-quality checks
  - Databricks Asset Bundle (databricks.yml)
"""

from __future__ import annotations

import re
from typing import Any

from .llm import (chat_json, last_content, last_error, last_finish_reason,
                   llm_enabled, model_name)
from .models import MappingEntry

#: Token budget for the three-file artifacts call. Three complete files in
#: one JSON object need headroom; chat_json() retries once higher still on
#: truncation before the export falls back to templates.
EXPORT_MAX_TOKENS = 12000

#: Read timeout for the artifacts call. A 12k-token generation legitimately
#: takes longer than the 60s META_TIMEOUT_SECONDS default; other calls keep
#: the default so real hangs still fail fast.
EXPORT_TIMEOUT_SECONDS = 180


def _slug(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return slug or "dataset"


def _col(path: str) -> str:
    return _slug(path.replace(".", "_"))


SPARK_TYPES = {
    "string": "STRING", "text": "STRING", "ip": "STRING", "mac": "STRING",
    "subnet": "STRING", "email": "STRING", "hostname": "STRING",
    "uri": "STRING", "code": "STRING", "id": "STRING", "iban": "STRING",
    "bic": "STRING", "object": "STRING", "json": "STRING", "version": "STRING",
    "integer": "BIGINT", "number": "BIGINT", "decimal": "DOUBLE",
    "boolean": "BOOLEAN", "datetime": "TIMESTAMP", "timestamp": "TIMESTAMP",
    "date": "DATE",
}


def spark_type(field_type: Optional[str]) -> str:
    return SPARK_TYPES.get((field_type or "").lower(), "STRING")


def _spark_expr(m: MappingEntry, target_types: dict[str, str]) -> str:
    if m.expression and m.transform in ("expression", "cast", "constant"):
        return m.expression
    if m.transform == "cast":
        return f"CAST(`{m.source}` AS {target_types.get(m.target, 'STRING')})"
    return f"`{m.source}`"


def template_pyspark(job: dict) -> str:
    lines = [
        '"""Auto-generated by Telemetry Foundry."""',
        "from pyspark.sql import SparkSession",
        "from pyspark.sql import functions as F",
        "",
        f"SOURCE_TABLE = \"{job['source_table']}\"",
        f"TARGET_TABLE = \"{job['catalog']}.{job['schema']}.{job['table']}\"",
        "",
        "",
        "def build(spark):",
        "    df = spark.table(SOURCE_TABLE)",
        "    return df.select(",
    ]
    for m in job["mappings"]:
        expr = _spark_expr(m, job["target_types"])
        lines.append(f"        F.expr(\"{expr}\").alias(\"{_col(m.target)}\"),")
    lines += [
        "    )",
        "",
        "",
        "def main():",
        "    spark = SparkSession.builder.getOrCreate()",
        "    out = build(spark)",
        "    out.write.mode(\"overwrite\").saveAsTable(TARGET_TABLE)",
        "    print(f\"Wrote {out.count()} rows to {TARGET_TABLE}\")",
        "",
        "",
        'if __name__ == "__main__":',
        "    main()",
        "",
    ]
    return "\n".join(lines)


def template_sql(job: dict) -> str:
    selects = ",\n  ".join(
        f"{_spark_expr(m, job['target_types'])} AS {_col(m.target)}"
        for m in job["mappings"]
    )
    return (
        f"-- Auto-generated by Telemetry Foundry\n"
        f"CREATE OR REPLACE TABLE {job['catalog']}.{job['schema']}.{job['table']} AS\n"
        f"SELECT\n  {selects}\nFROM {job['source_table']};\n"
    )


def template_dq(job: dict) -> str:
    lines = [
        '"""Data-quality checks for the curated table. Runs on Databricks or locally."""',
        "import sys",
        "from pyspark.sql import SparkSession",
        "from pyspark.sql import functions as F",
        "",
        f"TARGET_TABLE = \"{job['catalog']}.{job['schema']}.{job['table']}\"",
        "",
        "CHECKS = [",
    ]
    for col in job["required_cols"]:
        lines.append(f'    ("not_null:{col}", F.col("{col}").isNotNull()),')
    lines += [
        "]",
        "",
        "",
        "def main():",
        "    spark = SparkSession.builder.getOrCreate()",
        "    df = spark.table(TARGET_TABLE)",
        "    failures = []",
        "    n = df.count()",
        "    print(f\"row_count={n}\")",
        "    if n == 0:",
        "        failures.append(\"row_count: table is empty\")",
        "    for name, cond in CHECKS:",
        "        bad = df.filter(~cond).limit(1).count()",
        "        print(f\"{name}: {'PASS' if bad == 0 else 'FAIL'}\")",
        "        if bad:",
        "            failures.append(name)",
        "    if failures:",
        "        print(\"FAILED:\", failures)",
        "        sys.exit(1)",
        "    print(\"All data-quality checks passed.\")",
        "",
        "",
        'if __name__ == "__main__":',
        "    main()",
        "",
    ]
    return "\n".join(lines)


def template_dlt(job: dict) -> str:
    lines = [
        '"""Auto-generated by Telemetry Foundry (Delta Live Tables)."""',
        "import dlt",
        "from pyspark.sql import functions as F",
        "",
        f"SOURCE_TABLE = \"{job['source_table']}\"",
        "",
        "expectations = {",
    ]
    for col in job["required_cols"]:
        lines.append(f"    \"valid_{col}\": \"`{col}` IS NOT NULL\",")
    lines += [
        "}",
        "",
        "",
        "@dlt.table(",
        f"    name=\"{job['table']}\",",
        "    comment=\"Conformed OCSF table generated by Telemetry Foundry\",",
        ")",
        "@dlt.expect_all_or_drop(expectations)",
        f"def {job['table']}():",
        "    df = spark.read.table(SOURCE_TABLE)",
        "    return df.select(",
    ]
    for m in job["mappings"]:
        expr = _spark_expr(m, job["target_types"])
        lines.append(f"        F.expr(\"{expr}\").alias(\"{_col(m.target)}\"),")
    lines += ["    )", ""]
    return "\n".join(lines)


def template_bundle(job: dict) -> str:
    name = _slug(job["table"])
    return (
        "# Databricks Asset Bundle - deploy with: databricks bundle deploy\n"
        "bundle:\n"
        f"  name: {name}\n"
        "\n"
        "resources:\n"
        "  jobs:\n"
        f"    {name}_pipeline:\n"
        "      name: Standards pipeline\n"
        "      tasks:\n"
        "        - task_key: transform\n"
        "          spark_python_task:\n"
        "            python_file: ./transform.py\n"
        "        - task_key: dq_checks\n"
        "          depends_on: [transform]\n"
        "          spark_python_task:\n"
        "            python_file: ./dq_tests.py\n"
        "\n"
        "targets:\n"
        "  dev:\n"
        "    mode: development\n"
        "    default: true\n"
        "  prod:\n"
        "    mode: production\n"
    )


_EXPORT_SYSTEM = (
    "You generate Databricks-ready ETL artifacts. Return ONLY a JSON object "
    "with keys transform_py, transform_sql, dq_tests_py, each a string of "
    "complete file content with newlines escaped as \\n. Use the provided "
    "source table, target table, and column mappings (SQL expressions with "
    "aliases). Keep code runnable on Databricks. No markdown, no commentary."
)


def llm_artifacts(job: dict) -> Optional[dict[str, str]]:
    import json as _json

    user = _json.dumps({
        "source_table": job["source_table"],
        "target_table": f"{job['catalog']}.{job['schema']}.{job['table']}",
        "mappings": [
            {"source": m.source, "target": _col(m.target),
             "expression": _spark_expr(m, job["target_types"]),
             "transform": m.transform}
            for m in job["mappings"]
        ],
        "required_columns": job["required_cols"],
    }, default=str)
    data = chat_json(_EXPORT_SYSTEM, user, max_tokens=EXPORT_MAX_TOKENS,
                      timeout_seconds=EXPORT_TIMEOUT_SECONDS)
    if data and "transform_py" in data:
        return {
            "transform_py": data.get("transform_py", ""),
            "transform_sql": data.get("transform_sql", ""),
            "dq_tests_py": data.get("dq_tests_py", ""),
        }
    # The model sometimes answers with fenced code blocks instead of JSON.
    # Salvage those only when the response was complete: truncated output
    # must fall back to templates, never to half a file.
    if (last_finish_reason() or "").lower() not in ("length", "max_tokens"):
        salvaged = _salvage_fenced_blocks(last_content() or "")
        if salvaged:
            return salvaged
    return None


def _salvage_fenced_blocks(content: str) -> Optional[dict[str, str]]:
    """Extract the three artifacts from ``` fenced blocks, if present."""
    blocks = re.findall(r"```(\w*)\s*\n(.*?)```", content, re.DOTALL)
    bodies = [body.strip() for _, body in blocks if body.strip()]
    if len(bodies) < 3:
        return None
    langs = [(lang or "").lower() for lang, body in blocks if body.strip()]
    sql_idx = next((i for i, lang in enumerate(langs)
                    if lang == "sql"), None)
    if sql_idx is None:
        transform_py, transform_sql, dq_tests_py = bodies[0], bodies[1], bodies[2]
    else:
        others = [b for i, b in enumerate(bodies) if i != sql_idx]
        if len(others) < 2:
            return None
        transform_py, transform_sql, dq_tests_py = (
            others[0], bodies[sql_idx], others[1])
    if min(len(transform_py), len(transform_sql), len(dq_tests_py)) < 50:
        return None
    return {"transform_py": transform_py, "transform_sql": transform_sql,
            "dq_tests_py": dq_tests_py}


def _llm_files_honor_target(llm_files: dict[str, str], job: dict) -> bool:
    """Refuse LLM artifacts that ignore the entered catalog/table."""
    catalog = job["catalog"].lower()
    table = job["table"].lower()
    for key in ("transform_py", "transform_sql"):
        content = (llm_files.get(key) or "").lower()
        if catalog not in content or table not in content:
            return False
    return table in (llm_files.get("dq_tests_py") or "").lower()


def export_artifacts(
    mappings: list[MappingEntry],
    required_cols: list[str],
    catalog: str,
    schema: str,
    table: str,
    source_table: str,
    target_types: Optional[dict[str, str]] = None,
) -> dict[str, Any]:
    job = {
        "mappings": [m for m in mappings if m.target],
        "required_cols": required_cols,
        "catalog": catalog,
        "schema": schema,
        "table": _slug(table),
        "source_table": source_table,
        "target_types": target_types or {},
    }
    generated_by = "template"
    llm_error: Optional[str] = None
    llm_files: Optional[dict[str, str]] = None
    if llm_enabled():
        llm_files = llm_artifacts(job)
        if llm_files and _llm_files_honor_target(llm_files, job):
            generated_by = "meta"
        elif llm_files:
            llm_error = ("LLM output ignored the entered target "
                         f"({catalog}.{schema}.{job['table']}); "
                         "used template instead.")
            llm_files = None
        else:
            llm_error = last_error() or "LLM returned no usable artifacts"
    files = [
        {"path": "transform.py",
         "content": (llm_files or {}).get("transform_py") or template_pyspark(job)},
        {"path": "transform.sql",
         "content": (llm_files or {}).get("transform_sql") or template_sql(job)},
        {"path": "dq_tests.py",
         "content": (llm_files or {}).get("dq_tests_py") or template_dq(job)},
        # DLT pipeline is always templated: decorators don't survive LLM prose.
        {"path": "dlt_pipeline.py", "content": template_dlt(job)},
        {"path": "databricks.yml", "content": template_bundle(job)},
    ]
    if generated_by == "meta":
        return {"files": files, "generated_by": generated_by,
                "model": model_name(), "llm_error": None}
    return {"files": files, "generated_by": generated_by,
            "model": "template", "llm_error": llm_error}


